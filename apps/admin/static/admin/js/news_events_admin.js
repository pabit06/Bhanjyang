// Admin JavaScript for News Events

document.addEventListener('DOMContentLoaded', function() {
    // Initialize admin interface
    initializeNewsEventsAdmin();
    
    // Setup event listeners
    setupEventListeners();
    
    // Initialize charts if present
    initializeCharts();
});

function initializeNewsEventsAdmin() {
    console.log('News Events Admin initialized');
    
    // Add loading states to forms
    const forms = document.querySelectorAll('form');
    forms.forEach(form => {
        form.addEventListener('submit', function() {
            const submitBtn = form.querySelector('button[type="submit"]');
            if (submitBtn) {
                submitBtn.classList.add('loading');
                submitBtn.disabled = true;
            }
        });
    });
    
    // Enhance form controls
    enhanceFormControls();
    
    // Setup auto-save for drafts
    setupAutoSave();
}

function setupEventListeners() {
    // Bulk actions
    const bulkActionForm = document.getElementById('bulk-action-form');
    if (bulkActionForm) {
        bulkActionForm.addEventListener('submit', handleBulkAction);
    }
    
    // Content preview
    const previewBtns = document.querySelectorAll('.preview-btn');
    previewBtns.forEach(btn => {
        btn.addEventListener('click', handlePreview);
    });
    
    // Quick publish
    const quickPublishBtns = document.querySelectorAll('.quick-publish-btn');
    quickPublishBtns.forEach(btn => {
        btn.addEventListener('click', handleQuickPublish);
    });
    
    // Content sharing
    const shareBtns = document.querySelectorAll('.share-btn');
    shareBtns.forEach(btn => {
        btn.addEventListener('click', handleShare);
    });
}

function enhanceFormControls() {
    // Add character counters
    const textareas = document.querySelectorAll('textarea[maxlength]');
    textareas.forEach(textarea => {
        addCharacterCounter(textarea);
    });
    
    // Add slug auto-generation
    const titleFields = document.querySelectorAll('input[name="title"]');
    const slugFields = document.querySelectorAll('input[name="slug"]');
    
    if (titleFields.length > 0 && slugFields.length > 0) {
        titleFields[0].addEventListener('input', function() {
            if (!slugFields[0].value || slugFields[0].dataset.autoGenerated === 'true') {
                slugFields[0].value = slugify(this.value);
                slugFields[0].dataset.autoGenerated = 'true';
            }
        });
        
        slugFields[0].addEventListener('input', function() {
            this.dataset.autoGenerated = 'false';
        });
    }
    
    // Add image preview
    const imageInputs = document.querySelectorAll('input[type="file"][accept*="image"]');
    imageInputs.forEach(input => {
        input.addEventListener('change', handleImagePreview);
    });
}

function addCharacterCounter(textarea) {
    const maxLength = textarea.getAttribute('maxlength');
    if (!maxLength) return;
    
    const counter = document.createElement('div');
    counter.className = 'character-counter';
    counter.style.fontSize = '0.8rem';
    counter.style.color = '#666';
    counter.style.textAlign = 'right';
    counter.style.marginTop = '4px';
    
    textarea.parentNode.appendChild(counter);
    
    function updateCounter() {
        const remaining = maxLength - textarea.value.length;
        counter.textContent = `${remaining} characters remaining`;
        
        if (remaining < 50) {
            counter.style.color = '#DC3545';
        } else if (remaining < 100) {
            counter.style.color = '#FFC107';
        } else {
            counter.style.color = '#666';
        }
    }
    
    textarea.addEventListener('input', updateCounter);
    updateCounter();
}

function slugify(text) {
    return text
        .toLowerCase()
        .replace(/[^\w\s-]/g, '')
        .replace(/[\s_-]+/g, '-')
        .replace(/^-+|-+$/g, '');
}

function handleImagePreview(event) {
    const file = event.target.files[0];
    if (!file) return;
    
    const reader = new FileReader();
    reader.onload = function(e) {
        // Remove existing preview
        const existingPreview = event.target.parentNode.querySelector('.image-preview');
        if (existingPreview) {
            existingPreview.remove();
        }
        
        // Create new preview
        const preview = document.createElement('div');
        preview.className = 'image-preview';
        preview.style.marginTop = '10px';
        preview.innerHTML = `
            <img src="${e.target.result}" alt="Preview" style="max-width: 200px; max-height: 200px; border-radius: 4px; border: 1px solid #ddd;">
        `;
        
        event.target.parentNode.appendChild(preview);
    };
    reader.readAsDataURL(file);
}

function setupAutoSave() {
    const contentFields = document.querySelectorAll('textarea[name="content"]');
    contentFields.forEach(field => {
        let autoSaveTimeout;
        
        field.addEventListener('input', function() {
            clearTimeout(autoSaveTimeout);
            autoSaveTimeout = setTimeout(() => {
                autoSaveContent(field);
            }, 2000); // Auto-save after 2 seconds of inactivity
        });
    });
}

function autoSaveContent(field) {
    const form = field.closest('form');
    if (!form) return;
    
    const formData = new FormData(form);
    formData.append('auto_save', 'true');
    
    fetch(form.action || window.location.href, {
        method: 'POST',
        body: formData,
        headers: {
            'X-CSRFToken': document.querySelector('[name=csrfmiddlewaretoken]').value
        }
    })
    .then(response => response.json())
    .then(data => {
        if (data.success) {
            showMessage('Content auto-saved', 'success');
        }
    })
    .catch(error => {
        console.error('Auto-save failed:', error);
    });
}

function handleBulkAction(event) {
    event.preventDefault();
    
    const formData = new FormData(event.target);
    const action = formData.get('action');
    const contentIds = formData.get('content_ids');
    
    if (!action || !contentIds) {
        showMessage('Please select an action and content items', 'error');
        return;
    }
    
    if (!confirm(`Are you sure you want to ${action} the selected items?`)) {
        return;
    }
    
    const submitBtn = event.target.querySelector('button[type="submit"]');
    submitBtn.disabled = true;
    submitBtn.textContent = 'Processing...';
    
    fetch(event.target.action, {
        method: 'POST',
        body: formData,
        headers: {
            'X-CSRFToken': document.querySelector('[name=csrfmiddlewaretoken]').value
        }
    })
    .then(response => response.json())
    .then(data => {
        if (data.success) {
            showMessage(data.message, 'success');
            // Reload page or update UI
            setTimeout(() => {
                window.location.reload();
            }, 1500);
        } else {
            showMessage(data.message, 'error');
        }
    })
    .catch(error => {
        showMessage('Bulk action failed', 'error');
    })
    .finally(() => {
        submitBtn.disabled = false;
        submitBtn.textContent = 'Apply Action';
    });
}

function handlePreview(event) {
    event.preventDefault();
    
    const contentId = event.target.dataset.contentId;
    const contentType = event.target.dataset.contentType;
    
    if (!contentId || !contentType) {
        showMessage('Preview not available', 'error');
        return;
    }
    
    const previewUrl = `/admin/news-events/${contentType}/${contentId}/preview/`;
    window.open(previewUrl, '_blank');
}

function handleQuickPublish(event) {
    event.preventDefault();
    
    const contentId = event.target.dataset.contentId;
    const contentType = event.target.dataset.contentType;
    
    if (!contentId || !contentType) {
        showMessage('Quick publish not available', 'error');
        return;
    }
    
    if (!confirm('Are you sure you want to publish this content?')) {
        return;
    }
    
    const originalText = event.target.textContent;
    event.target.disabled = true;
    event.target.textContent = 'Publishing...';
    
    fetch(`/admin/news-events/${contentType}/${contentId}/quick-publish/`, {
        method: 'POST',
        headers: {
            'X-CSRFToken': document.querySelector('[name=csrfmiddlewaretoken]').value
        }
    })
    .then(response => response.json())
    .then(data => {
        if (data.success) {
            showMessage('Content published successfully', 'success');
            event.target.textContent = 'Published';
            event.target.classList.add('published');
        } else {
            showMessage(data.message, 'error');
            event.target.textContent = originalText;
            event.target.disabled = false;
        }
    })
    .catch(error => {
        showMessage('Publishing failed', 'error');
        event.target.textContent = originalText;
        event.target.disabled = false;
    });
}

function handleShare(event) {
    event.preventDefault();
    
    const contentId = event.target.dataset.contentId;
    const contentType = event.target.dataset.contentType;
    const title = event.target.dataset.title;
    
    if (!contentId || !contentType) {
        showMessage('Share not available', 'error');
        return;
    }
    
    // Create share modal
    const modal = createShareModal(contentId, contentType, title);
    document.body.appendChild(modal);
    
    // Show modal
    modal.style.display = 'block';
    modal.classList.add('show');
}

